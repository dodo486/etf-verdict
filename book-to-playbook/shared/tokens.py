"""정량 토큰 사전 — 파이프라인 전체의 단일 기준.

'저자가 숫자로 말한 것'을 뽑는 정규식과 표기 정규화. 원래 verify_coverage.py(구간②)
안에 있었지만 구간①(book_source·창작검사)·구간③(규칙↔수집 대조)도 같은 정의를
써야 한다 — 토큰 정의가 둘이면 검사들이 서로 다른 것을 세고, 그 순간 대조는 거짓이
된다. 그래서 공통층으로 나왔다.
"""
import re

# 정량 토큰 — 저자가 숫자로 말한 것만
TOKEN_RE = re.compile(
    r"(\d+\s*~\s*\d+\s*%p?"          # 7~10%
    r"|[+-]?\d+(?:\.\d+)?\s*%p"      # 0.1%p
    r"|[+-]?\d+(?:\.\d+)?\s*%"       # -5%, 30%
    r"|\d+\s*거래일"                  # 2거래일
    r"|\d+\s*일선"                    # 20일선
    r"|\d+(?:\.\d+)?\s*배"            # 1.5배
    r"|\d+\s*개"                      # 3개
    r"|\d+\s*분)"                     # 30분
)


def norm(t):
    return re.sub(r"\s+", "", t).replace("＋", "+")
